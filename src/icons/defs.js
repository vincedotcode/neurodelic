function spiral(cx, cy, r, turns) {
  const pts = [];
  const steps = 90;
  for (let i = 0; i <= steps; i++) {
    const t = (i / steps) * turns * Math.PI * 2;
    const rr = (i / steps) * r;
    pts.push(cx + Math.cos(t) * rr, cy + Math.sin(t) * rr);
  }
  return pts;
}
function ellipse(cx, cy, rx, ry, rotDeg) {
  const pts = [];
  const rot = (rotDeg * Math.PI) / 180, c = Math.cos(rot), s = Math.sin(rot);
  for (let i = 0; i <= 48; i++) {
    const a = (i / 48) * Math.PI * 2;
    const x = Math.cos(a) * rx, y = Math.sin(a) * ry;
    pts.push(cx + x * c - y * s, cy + x * s + y * c);
  }
  return pts;
}
function waveLine(x0, y, len, amp, waves) {
  const pts = [];
  for (let i = 0; i <= 40; i++) {
    const t = i / 40;
    pts.push(x0 + t * len, y + Math.sin(t * waves * Math.PI * 2) * amp);
  }
  return pts;
}
function gear(cx, cy, ro, ri, teeth) {
  const pts = [];
  const n = teeth * 4;
  for (let i = 0; i <= n; i++) {
    const a = (i / n) * Math.PI * 2;
    const r = i % 4 < 2 ? ro : ri;
    pts.push(cx + Math.cos(a) * r, cy + Math.sin(a) * r);
  }
  return pts;
}

